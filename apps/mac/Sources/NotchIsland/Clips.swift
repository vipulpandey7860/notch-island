// Clips: what you've copied lately and the screenshots you've taken, in the open island's Clips tab. Click one to
// copy it again, or drag it out. Kept in memory only, so it's gone when you quit; anything password managers mark
// as secret is never kept.
import AppKit
import QuickLookThumbnailing

final class Clips {
    enum Content {
        case text(String), image(NSImage), file(URL)
    }
    struct Clip {
        let id = UUID()
        let content: Content
        let date: Date
        let screenshot: Bool
    }

    static let limit = 30
    private(set) var items: [Clip] = []  // newest first
    var onChange: () -> Void = {}
    var onScreenshot: (URL) -> Void = { _ in }
    private var seen = NSPasteboard.general.changeCount
    private var query: NSMetadataQuery?
    // nspasteboard.org's markers, which password managers use for what they copy
    private static let secret: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                              "org.nspasteboard.AutoGeneratedType"]

    /// Screenshots, wherever they're saved: Spotlight tags them, in any language.
    func start() {
        let q = NSMetadataQuery()
        q.predicate = NSPredicate(format: "kMDItemIsScreenCapture == 1 AND kMDItemFSCreationDate >= %@", Date() as NSDate)
        q.searchScopes = [NSMetadataQueryUserHomeScope]
        NotificationCenter.default.addObserver(forName: .NSMetadataQueryDidUpdate, object: q, queue: .main) { [weak self] n in
            for item in n.userInfo?[NSMetadataQueryUpdateAddedItemsKey] as? [NSMetadataItem] ?? [] {
                guard let path = item.value(forAttribute: NSMetadataItemPathKey) as? String else { continue }
                self?.add(.file(URL(fileURLWithPath: path)), screenshot: true)
                self?.onScreenshot(URL(fileURLWithPath: path))
            }
        }
        q.start()
        query = q
    }

    /// Call once a second: the pasteboard has no "changed" notification, only a counter.
    func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != seen else { return }
        seen = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard Pref.keepClips.isOn, types.isDisjoint(with: Self.secret) else { return }
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            urls.prefix(5).reversed().forEach { add(.file($0)) }
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(.text(s))  // text first: rich text often comes with a picture of itself too
        } else if let image = NSImage(pasteboard: pb) {
            add(.image(image))
        }
    }

    /// Puts a clip back on the pasteboard, and at the top of the list.
    func copy(_ id: UUID) {
        guard let c = items.first(where: { $0.id == id }) else { return }
        let pb = NSPasteboard.general
        pb.clearContents()
        switch c.content {
        case .text(let s): pb.setString(s, forType: .string)
        case .image(let i): pb.writeObjects([i])
        case .file(let u): pb.writeObjects([u as NSURL])
        }
        seen = pb.changeCount  // our own copy isn't a new clip
        items.removeAll { $0.id == id }
        items.insert(c, at: 0)
        onChange()
    }

    func remove(_ id: UUID) { items.removeAll { $0.id == id }; onChange() }
    func clear() { items.removeAll(); onChange() }

    func add(_ content: Content, screenshot: Bool = false) {
        items.removeAll { old in  // copying the same thing again moves it up
            switch (old.content, content) {
            case (.text(let a), .text(let b)): return a == b
            case (.file(let a), .file(let b)): return a == b
            default: return false
            }
        }
        items.insert(Clip(content: content, date: Date(), screenshot: screenshot), at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
        onChange()
    }
}

// MARK: - The Clips tab

/// The list in the notepad card's Clips tab.
final class ClipsList: NSView {
    private let scroll = NSScrollView(), rows = FlippedView()
    private let empty = NSTextField(wrappingLabelWithString: "Things you copy and screenshots you take show up here.")
    private unowned let clips: Clips
    var onCopied: () -> Void = {}

    init(frame: NSRect, clips: Clips) {
        self.clips = clips
        super.init(frame: frame)
        scroll.frame = bounds
        scroll.drawsBackground = false
        scroll.hasVerticalScroller = true; scroll.scrollerStyle = .overlay; scroll.scrollerKnobStyle = .light; scroll.autohidesScrollers = true
        rows.frame = NSRect(x: 0, y: 0, width: frame.width, height: 0)
        scroll.documentView = rows
        empty.font = .systemFont(ofSize: 12.5); empty.textColor = white(0.3)
        empty.frame = NSRect(x: 0, y: frame.height - 40, width: frame.width, height: 40)
        addSubview(scroll); addSubview(empty)
    }
    required init?(coder: NSCoder) { fatalError() }

    func reload() {
        rows.subviews.forEach { $0.removeFromSuperview() }
        var y: CGFloat = 0
        for c in clips.items {
            let r = ClipRow(c, width: rows.frame.width)
            r.onCopy = { [unowned self] in self.clips.copy(c.id); self.onCopied() }
            r.onRemove = { [unowned self] in self.clips.remove(c.id) }
            r.frame.origin.y = y
            y += r.frame.height
            rows.addSubview(r)
        }
        rows.frame.size.height = max(y, scroll.frame.height)
        empty.isHidden = !clips.items.isEmpty
    }
}

/// One clip: a thumbnail, what it is, and when. Click to copy it, drag it out to use it somewhere.
final class ClipRow: FlippedView, NSDraggingSource {
    private static let ago: RelativeDateTimeFormatter = { let f = RelativeDateTimeFormatter(); f.unitsStyle = .short; return f }()
    let clip: Clips.Clip
    var onCopy: () -> Void = {}
    var onRemove: () -> Void = {}
    private var downAt: NSPoint?
    private var remove: IconButton!

    init(_ c: Clips.Clip, width: CGFloat) {
        clip = c
        super.init(frame: NSRect(x: 0, y: 0, width: width, height: 38))
        wantsLayer = true; layer!.cornerRadius = 8
        let thumb = NSImageView(frame: NSRect(x: 4, y: 6, width: 26, height: 26))
        thumb.wantsLayer = true; thumb.layer!.cornerRadius = 5; thumb.layer!.masksToBounds = true
        thumb.imageScaling = .scaleProportionallyUpOrDown
        let title: String, kind: String
        switch c.content {
        case .text(let s):
            thumb.image = sym("text.alignleft", 13, .medium); thumb.contentTintColor = white(0.5); thumb.imageScaling = .scaleNone
            thumb.layer!.backgroundColor = white(0.08).cgColor
            title = s.trimmingCharacters(in: .whitespacesAndNewlines).components(separatedBy: .newlines).first ?? s
            kind = "Text"
        case .image(let i):
            thumb.image = i
            title = "Image, \(Int(i.size.width)) × \(Int(i.size.height))"
            kind = "Image"
        case .file(let u):
            thumb.image = NSWorkspace.shared.icon(forFile: u.path)
            let req = QLThumbnailGenerator.Request(fileAt: u, size: CGSize(width: 26, height: 26), scale: 2, representationTypes: .thumbnail)
            Task { @MainActor in
                if let rep = try? await QLThumbnailGenerator.shared.generateBestRepresentation(for: req) { thumb.image = rep.nsImage }
            }
            title = FileManager.default.displayName(atPath: u.path)
            kind = c.screenshot ? "Screenshot" : "File"
        }
        let name = label(title, 12, .medium, white(0.88)); put(name, 38, 13, width - 38 - 24)
        let when = -c.date.timeIntervalSinceNow < 60 ? "just now" : Self.ago.localizedString(for: c.date, relativeTo: Date())
        let detail = label("\(kind) · \(when)", 10.5, .medium, white(0.4)); put(detail, 38, 27, width - 38 - 24)
        remove = IconButton("xmark", size: 18, point: 9, label: "Remove from Clips") { [unowned self] in self.onRemove() }
        remove.image.contentTintColor = white(0.6)
        remove.frame.origin = NSPoint(x: width - 20, y: 10)
        remove.isHidden = true
        [thumb, name, detail, remove].forEach(addSubview)
        toolTip = "Click to copy, or drag it out"
        setAccessibilityElement(true); setAccessibilityRole(.button); setAccessibilityLabel("\(kind): \(title)")
        addTrackingArea(NSTrackingArea(rect: .zero, options: [.mouseEnteredAndExited, .activeAlways, .inVisibleRect], owner: self, userInfo: nil))
    }
    required init?(coder: NSCoder) { fatalError() }

    override func hitTest(_ p: NSPoint) -> NSView? {
        let v = super.hitTest(p)
        return v === remove ? v : (v == nil ? nil : self)
    }
    override func acceptsFirstMouse(for e: NSEvent?) -> Bool { true }
    override func mouseEntered(with e: NSEvent) { layer!.backgroundColor = white(0.06).cgColor; remove.isHidden = false }
    override func mouseExited(with e: NSEvent) { layer!.backgroundColor = nil; remove.isHidden = true }
    override func mouseDown(with e: NSEvent) { downAt = convert(e.locationInWindow, from: nil) }
    override func mouseUp(with e: NSEvent) {
        guard downAt != nil else { return }
        downAt = nil
        onCopy()
    }
    override func accessibilityPerformPress() -> Bool { onCopy(); return true }

    override func mouseDragged(with e: NSEvent) {
        guard let p = downAt else { return }
        downAt = nil
        let writer: NSPasteboardWriting, image: NSImage?
        switch clip.content {
        case .text(let s): writer = s as NSString; image = sym("text.alignleft", 20)
        case .image(let i): writer = i; image = i
        case .file(let u): writer = u as NSURL; image = NSWorkspace.shared.icon(forFile: u.path)
        }
        let item = NSDraggingItem(pasteboardWriter: writer)
        item.setDraggingFrame(NSRect(x: p.x - 20, y: p.y - 20, width: 40, height: 40), contents: image)
        beginDraggingSession(with: [item], event: e, source: self)
    }
    func draggingSession(_ s: NSDraggingSession, sourceOperationMaskFor c: NSDraggingContext) -> NSDragOperation {
        c == .outsideApplication ? .copy : []
    }
}
